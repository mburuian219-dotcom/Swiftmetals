import React, { useState } from "react";

interface InvoiceFormProps {
  onSubmit: (data: any) => void;
}

const InvoiceForm: React.FC<InvoiceFormProps> = ({ onSubmit }) => {
  const [form, setForm] = useState({
    sale_id: "",
    amount_paid: "",
    generated_by: "",
  });

  const handleChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    setForm({ ...form, [e.target.name]: e.target.value });
  };

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    onSubmit(form);
  };

  return (
    <form onSubmit={handleSubmit} className="space-y-4">
      <div>
        <label className="block text-sm font-medium">Sale ID</label>
        <input
          name="sale_id"
          value={form.sale_id}
          onChange={handleChange}
          className="w-full p-2 border rounded-lg"
          placeholder="Enter sale ID"
        />
      </div>
      <div>
        <label className="block text-sm font-medium">Amount Paid</label>
        <input
          name="amount_paid"
          value={form.amount_paid}
          onChange={handleChange}
          className="w-full p-2 border rounded-lg"
          placeholder="Enter amount paid"
        />
      </div>
      <div>
        <label className="block text-sm font-medium">Generated By</label>
        <input
          name="generated_by"
          value={form.generated_by}
          onChange={handleChange}
          className="w-full p-2 border rounded-lg"
          placeholder="User ID"
        />
      </div>
      <button className="bg-blue-600 text-white px-4 py-2 rounded-lg hover:bg-blue-700">
        Generate Invoice
      </button>
    </form>
  );
};

export default InvoiceForm;
